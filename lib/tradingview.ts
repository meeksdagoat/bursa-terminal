/** Maps a Bursa stock code (`4707`, `4707.KL`) to the TradingView short name (`NESTLE`). */
export function lookupBursaShortName(token: string): string | undefined {
  const code = token.replace(/\.KL$/i, "").trim();
  return TV_TICKER_BY_CODE[code];
}

function resolveTickerToken(token: string): string {
  const code = token.replace(/\.KL$/i, "").trim();
  if (!code) return code;
  return lookupBursaShortName(code) ?? code.toUpperCase();
}

export function toTradingViewSymbol(symbol: string): string {
  const raw = symbol.trim();
  if (!raw) return "MYX:MAYBANK";

  if (raw === "^KLSE" || raw.toUpperCase() === "KLSE") return "MYX:KLSE";

  const colon = raw.indexOf(":");
  if (colon > 0) {
    let exchange = raw.slice(0, colon).toUpperCase();
    const rest = raw.slice(colon + 1);
    if (exchange === "BURSA") exchange = "MYX";
    // MYX:4707 must become MYX:NESTLE — TradingView indexes Bursa by short name.
    const ticker = exchange === "MYX" ? resolveTickerToken(rest) : rest;
    return `${exchange}:${ticker}`;
  }

  return `MYX:${resolveTickerToken(raw)}`;
}
